/**
 * Find article by ID or Title or Target Problem
 */
export function findArticle(query = '') {
  if (!query) return null;
  const q = String(query).toLowerCase().trim();
  
  // Exact ID
  const byId = UDO_ARTICLES.find(a => a.id.toLowerCase() === q);
  if (byId) return byId;

  // Title match
  const byTitle = UDO_ARTICLES.find(a => a.title.toLowerCase().includes(q) || q.includes(a.title.toLowerCase()));
  if (byTitle) return byTitle;

  // Problem / keyword match
  const byProblem = UDO_ARTICLES.find(a => {
    return (a.target_problems || []).some(tp => q.includes(tp.toLowerCase()) || tp.toLowerCase().includes(q));
  });
  if (byProblem) return byProblem;

  return null;
}
